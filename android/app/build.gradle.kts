    ndkVersion = "30.0.16248370"

    defaultConfig {
        applicationId = "xyz.nshnt.ferrokey"
        minSdk = minSdkVersion
        targetSdk = 37
        versionCode = 1
        versionName = "0.1.0"
        ndk { abiFilters += rustAbis }
    }

