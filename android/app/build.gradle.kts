// --- Rust core -------------------------------------------------------------
//
// The ferrokey-mobile crate is cross-compiled with cargo-ndk and its Kotlin
// bindings are generated by UniFFI, both as part of the normal Gradle build.

val cargoWorkspace: File = rootDir.parentFile

/** Cargo inputs, so Gradle can skip the Rust build when nothing changed. */
val rustSources = files(
    cargoWorkspace.resolve("Cargo.toml"),
    cargoWorkspace.resolve("Cargo.lock"),
    fileTree(cargoWorkspace.resolve("crates")),
)

abstract class BuildRustTask @Inject constructor(private val exec: ExecOperations) : DefaultTask() {
    @get:InputFiles
    @get:PathSensitive(PathSensitivity.RELATIVE)
    abstract val sources: ConfigurableFileCollection

    @get:Internal
    abstract val workspace: DirectoryProperty

    @get:Internal
    abstract val ndkDirectory: DirectoryProperty

    @get:Input
    abstract val abis: ListProperty<String>

    @get:Input
    abstract val minSdk: Property<Int>

    @get:OutputDirectory
    abstract val outputDir: DirectoryProperty

    @TaskAction
    fun build() {
        exec.exec {
            workingDir = workspace.get().asFile
            environment("ANDROID_NDK_HOME", ndkDirectory.get().asFile.absolutePath)
            commandLine(
                buildList {
                    addAll(listOf("cargo", "ndk", "--platform", minSdk.get().toString()))
                    abis.get().forEach { addAll(listOf("--target", it)) }
                    addAll(listOf("--output-dir", outputDir.get().asFile.absolutePath))
                    addAll(listOf("build", "--release", "--package", "ferrokey-mobile"))
                },
            )
        }
    }
}

abstract class GenerateBindingsTask @Inject constructor(private val exec: ExecOperations) : DefaultTask() {
    @get:InputFile
    @get:PathSensitive(PathSensitivity.NONE)
    abstract val library: RegularFileProperty

    @get:Internal
    abstract val workspace: DirectoryProperty

    @get:OutputDirectory
    abstract val outputDir: DirectoryProperty

    @TaskAction
    fun generate() {
        outputDir.get().asFile.deleteRecursively()
        exec.exec {
            workingDir = workspace.get().asFile
            commandLine(
                "cargo", "run", "--quiet", "--package", "uniffi-bindgen", "--",
                "generate", "--library", library.get().asFile.absolutePath,
                "--language", "kotlin", "--no-format",
                "--out-dir", outputDir.get().asFile.absolutePath,
            )
        }
    }
}

val buildRust = tasks.register<BuildRustTask>("buildRust") {
    sources.from(rustSources)
    workspace.set(cargoWorkspace)
    ndkDirectory.set(androidComponents.sdkComponents.ndkDirectory)
    abis.set(rustAbis)
    minSdk.set(minSdkVersion)
    outputDir.set(layout.buildDirectory.dir("rust/jniLibs"))
}

val generateBindings = tasks.register<GenerateBindingsTask>("generateBindings") {
    // Bindings are ABI-independent; any one of the built libraries will do.
    library.set(buildRust.flatMap { it.outputDir.file("${rustAbis.first()}/libferrokey_mobile.so") })
    workspace.set(cargoWorkspace)
    outputDir.set(layout.buildDirectory.dir("generated/source/uniffi"))
}

androidComponents.onVariants { variant ->
    variant.sources.jniLibs?.addGeneratedSourceDirectory(buildRust, BuildRustTask::outputDir)
    variant.sources.kotlin?.addGeneratedSourceDirectory(generateBindings, GenerateBindingsTask::outputDir)
}
